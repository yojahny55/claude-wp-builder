#!/usr/bin/env bash
# Rebuilds references/design-md/INDEX.md from each vendored DESIGN.md's front
# matter. Industry and tone are read from the description by keyword — both
# the single-line `description: value` form and the YAML block-scalar
# `description: |` form (followed by indented lines) — lowercased before
# matching. Display face prefers the fontFamily under the first typography
# key named `display*`, falling back to the first fontFamily in the file only
# when no such key exists. A file the heuristics still cannot classify gets
# "general" / "unknown".
#
# Hand corrections live in INDEX.overrides next to INDEX.md, never in INDEX.md
# itself: one `<domain> <industry> [<tone>]` per line (`#` comments allowed),
# applied after the heuristic. Regenerating therefore keeps them. A line naming a
# domain that has no DESIGN.md fails the run, so a renamed or removed vendor cannot
# leave a correction silently unused.
set -euo pipefail
# Byte order for the glob below: a locale-aware collation sorts `bmw/` before `bmw-m/` on one
# machine and after it on another, and the versioned index must equal any regeneration.
export LC_ALL=C
cd "$(dirname "$0")/.."
d=skills/wp-demo-craft/references/design-md

tmp=$(mktemp "$d/.INDEX.md.XXXXXX")
trap 'rm -f "$tmp"' EXIT
# mktemp creates 0600; copying the current file first keeps its mode, so the rename
# below does not leave INDEX.md unreadable to the group. The contents are replaced.
[ -f "$d/INDEX.md" ] && \cp -pf "$d/INDEX.md" "$tmp"

ov="$d/INDEX.overrides"
if [ -f "$ov" ]; then
  while read -r odom _rest || [ -n "${odom:-}" ]; do
    case "$odom" in ''|'#'*) continue ;; esac
    [ -f "$d/$odom/DESIGN.md" ] || { echo "error: $ov names '$odom', which has no DESIGN.md" >&2; exit 1; }
  done < "$ov"
fi

{
  cat <<'EOF'
# Catalogue index

Generated by `bin/design-md-index.sh`; do not edit by hand. Industry and tone
come from a keyword heuristic, corrected per domain by `INDEX.overrides`: fix a
wrong row there and re-run the script.

One row per vendored DESIGN.md. Pick two or three nearest matches by industry
and tone; read only those files. Never copy a row's tokens verbatim into a client
DESIGN.md: the catalogue is vocabulary, the client docs are the source.

| domain | industry | tone | display | accent |
|---|---|---|---|---|
EOF
  for f in "$d"/*/DESIGN.md; do
    dom=$(basename "$(dirname "$f")")
    desc=$(awk '
      /^description: \|/ { mode=1; next }
      mode==0 && /^description:/ { sub(/^description: */, ""); print; exit }
      mode==1 {
        if ($0 !~ /^  /) { print buf; exit }
        line=$0; sub(/^  /, "", line)
        buf = (buf=="" ? line : buf " " line)
        next
      }
      END { if (mode==1) print buf }
    ' "$f")
    accent=$(awk '/^  primary: / { gsub(/"/, "", $2); print $2; exit }' "$f")
    canvas=$(awk '/^  canvas: / { gsub(/"/, "", $2); print $2; exit }' "$f")
    display=$(awk '
      /^  display[a-zA-Z0-9_-]*:$/ { getline nxt; sub(/^ *fontFamily: */, "", nxt); print nxt; exit }
    ' "$f")
    if [ -z "$display" ]; then
      display=$(awk '/fontFamily:/ { sub(/^ *fontFamily: */, ""); print; exit }' "$f")
    fi
    tone=unknown
    case "$canvas" in
      '#0'*|'#1'*|'#2'*) tone=dark ;;
      '#f'*|'#F'*|'#e'*|'#E'*) tone=light ;;
    esac
    industry=general
    # `api` and `car` match as whole words only: as substrings they hit "capital",
    # "rapid", "card", "care". Padded with spaces so a word at either end matches too.
    words=" $(echo "$desc" | tr 'A-Z' 'a-z' | tr -c 'a-z0-9\n' ' ') "
    case "$words" in
      *fintech*|*bank*|*payment*|*finance*) industry=finance ;;
      *developer*|*devtool*|*" api "*|*" apis "*|*infrastructure*) industry=devtools ;;
      *saas*|*product*|*software*) industry=saas ;;
      *commerce*|*shop*|*retail*|*store*) industry=commerce ;;
      *agency*|*studio*|*portfolio*) industry=agency ;;
      *health*|*medical*|*wellness*) industry=health ;;
      *travel*|*hotel*|*hospitality*) industry=hospitality ;;
      *" car "*|*" cars "*|*automotive*|*vehicle*) industry=automotive ;;
    esac
    if [ -f "$ov" ]; then
      read -r _o oind otone < <(awk -v d="$dom" '!/^[[:space:]]*#/ && $1 == d { print; exit }' "$ov") || true
      [ -n "${oind:-}" ] && industry="$oind"
      [ -n "${otone:-}" ] && tone="$otone"
      oind='' otone=''
    fi
    echo "| $dom | $industry | $tone | ${display:-unknown} | ${accent:-unknown} |"
  done
} > "$tmp"
mv -f "$tmp" "$d/INDEX.md"
echo "wrote $d/INDEX.md"
