#!/usr/bin/env bash
# Rebuilds references/design-md/INDEX.md from each vendored DESIGN.md's front
# matter. Industry and tone are read from the description by keyword — both
# the single-line `description: value` form and the YAML block-scalar
# `description: |` form (followed by indented lines) — lowercased before
# matching. Display face prefers the fontFamily under the first typography
# key named `display*`, falling back to the first fontFamily in the file only
# when no such key exists. A file the heuristics still cannot classify gets
# "general" / "unknown" and a human edits the row.
#
# This OVERWRITES INDEX.md, including any hand-corrected rows — see the
# warning printed below before it writes.
set -euo pipefail
cd "$(dirname "$0")/.."
d=skills/wp-demo-craft/references/design-md

echo "warning: about to overwrite $d/INDEX.md — any hand-corrected industry or" >&2
echo "tone values will be replaced by the keyword heuristic below. Diff the" >&2
echo "result against git before committing and redo hand corrections that still apply." >&2

{
  cat <<'EOF'
# Catalogue index

Generated by `bin/design-md-index.sh`. Some rows have been hand-corrected
where the keyword heuristic below was wrong; re-running the script replaces
those corrections, so diff against git and redo them.

One row per vendored DESIGN.md. Pick two or three nearest matches by industry
and tone; read only those files. Never copy a row's tokens verbatim into a client
DESIGN.md: the catalogue is vocabulary, the client docs are the source.

| domain | industry | tone | display | accent |
|---|---|---|---|---|
EOF
  for f in "$d"/*/DESIGN.md; do
    dom=$(basename "$(dirname "$f")")
    desc=$(awk '
      /^description: \|/ { mode=1; next }
      mode==0 && /^description:/ { sub(/^description: */, ""); print; exit }
      mode==1 {
        if ($0 !~ /^  /) { print buf; exit }
        line=$0; sub(/^  /, "", line)
        buf = (buf=="" ? line : buf " " line)
        next
      }
      END { if (mode==1) print buf }
    ' "$f")
    accent=$(awk '/^  primary: / { gsub(/"/, "", $2); print $2; exit }' "$f")
    canvas=$(awk '/^  canvas: / { gsub(/"/, "", $2); print $2; exit }' "$f")
    display=$(awk '
      /^  display[a-zA-Z0-9_-]*:$/ { getline nxt; sub(/^ *fontFamily: */, "", nxt); print nxt; exit }
    ' "$f")
    if [ -z "$display" ]; then
      display=$(awk '/fontFamily:/ { sub(/^ *fontFamily: */, ""); print; exit }' "$f")
    fi
    tone=unknown
    case "$canvas" in
      '#0'*|'#1'*|'#2'*) tone=dark ;;
      '#f'*|'#F'*|'#e'*|'#E'*|'#ffffff') tone=light ;;
    esac
    industry=general
    case "$(echo "$desc" | tr 'A-Z' 'a-z')" in
      *fintech*|*bank*|*payment*|*finance*) industry=finance ;;
      *developer*|*devtool*|*api*|*infrastructure*) industry=devtools ;;
      *saas*|*product*|*software*) industry=saas ;;
      *commerce*|*shop*|*retail*|*store*) industry=commerce ;;
      *agency*|*studio*|*portfolio*) industry=agency ;;
      *health*|*medical*|*wellness*) industry=health ;;
      *travel*|*hotel*|*hospitality*) industry=hospitality ;;
      *car*|*automotive*|*vehicle*) industry=automotive ;;
    esac
    echo "| $dom | $industry | $tone | ${display:-unknown} | ${accent:-unknown} |"
  done
} > "$d/INDEX.md"
echo "wrote $d/INDEX.md"
