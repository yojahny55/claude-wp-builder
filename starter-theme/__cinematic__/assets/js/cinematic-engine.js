/* __starter__ — cinematic engine
   --------------------------------------------------------
   DESKTOP  → scroll-scrub. WebCodecs → canvas when supported (frame-perfect,
              smooth reverse); falls back to video.currentTime on old browsers.
   MOBILE   → native autoplay-loop (the inline .scene__video-mobile plays itself);
              JS only reveals copy + pauses offscreen clips for battery.
   REDUCED  → prefers-reduced-motion: no scrub, posters only.

   Render-engine rationale: see cinematic-scroll-kit
   skills/07-scroll-scrub-rendering.md. video.currentTime is not frame-accurate
   and cannot decode backward — the cause of "stuck / jumps to end / reverse
   stutter". WebCodecs decodes the exact requested frame.

   This engine is intentionally robust to missing optional DOM (no hard refs
   to a progress bar / curtain / pricing section) so it works on any
   ACF-driven front page generated by the wp-cinematic agent.
*/
(() => {
  'use strict';

  const mqMobile  = window.matchMedia('(max-width: 1024px), (pointer: coarse) and (max-width: 1024px)');
  const mqReduced = window.matchMedia('(prefers-reduced-motion: reduce)');

  const stage    = document.querySelector('.stage');
  const videos   = Array.from(document.querySelectorAll('.stage__v'));
  const canvases = Array.from(document.querySelectorAll('.stage__c'));
  const scenes   = Array.from(document.querySelectorAll('.scene'));

  if (!scenes.length) return;

  const isMobile = mqMobile.matches;
  const reduced  = mqReduced.matches
    || document.documentElement.classList.contains('prefers-reduced-motion');

  // Re-init cleanly when crossing the breakpoint.
  mqMobile.addEventListener('change', () => location.reload());

  // Anchor scrolling (works in both modes; uses Lenis if present).
  document.querySelectorAll('a[href^="#"]').forEach(a => {
    a.addEventListener('click', e => {
      const id = a.getAttribute('href');
      if (!id || id.length < 2) return;
      const el = document.querySelector(id);
      if (!el) return;
      e.preventDefault();
      if (window.lenis) window.lenis.scrollTo(el, { duration: 1.4 });
      else el.scrollIntoView({ behavior: 'smooth', block: 'start' });
    });
  });

  function setVeil(scene) {
    if (stage) stage.setAttribute('data-veil', (scene && scene.dataset.veil) || 'left');
  }

  // ── shared <video> ready helper (legacy path + mobile) ─────────────────
  function readyVideo(v) {
    return new Promise(resolve => {
      if (!v) return resolve();
      const ok = () => { if (v.duration && !isNaN(v.duration)) resolve(); };
      if (v.readyState >= 2 && v.duration) return resolve();
      v.addEventListener('loadedmetadata', ok, { once: true });
      v.addEventListener('loadeddata', ok, { once: true });
      v.addEventListener('canplay', ok, { once: true });
      const src = (isMobile && v.dataset.srcMobile) ? v.dataset.srcMobile : v.dataset.src;
      if (!v.src && src) { v.src = src; v.load(); }
    });
  }

  // ── REDUCED MOTION: posters only, no scrub, no boot ────────────────────
  if (reduced) {
    document.body.classList.add('reduced-motion');
    scenes.forEach(s => s.classList.add('in'));
    setVeil(scenes[0]);
    return;
  }

  // ── MOBILE: inline .scene__video-mobile autoplays itself; reveal + thrift ─
  if (isMobile) {
    document.body.classList.add('is-mobile');

    const ioReveal = new IntersectionObserver(entries => {
      entries.forEach(e => {
        if (e.isIntersecting) e.target.classList.add('in');
        else if (e.boundingClientRect.top > 0) e.target.classList.remove('in');
      });
    }, { threshold: 0.25 });
    scenes.forEach(s => ioReveal.observe(s));

    // Pause offscreen mobile clips for battery; set veil to centred scene.
    const ioActive = new IntersectionObserver(entries => {
      let best = null;
      entries.forEach(e => {
        if (e.isIntersecting && (!best || e.intersectionRatio > best.intersectionRatio)) best = e;
      });
      if (!best) return;
      setVeil(best.target);
      scenes.forEach(s => {
        const v = s.querySelector('.scene__video-mobile');
        if (!v) return;
        if (s === best.target) { v.play?.().catch(() => {}); }
        else if (!v.paused) { v.pause(); }
      });
    }, { rootMargin: '-35% 0% -35% 0%', threshold: 0 });
    scenes.forEach(s => ioActive.observe(s));

    setVeil(scenes[0]);
    return;
  }

  // ── DESKTOP: requires GSAP + ScrollTrigger (+ optional Lenis) ───────────
  if (typeof window.gsap === 'undefined' || typeof window.ScrollTrigger === 'undefined') {
    // Dependencies didn't load — degrade gracefully to posters.
    document.body.classList.add('reduced-motion');
    scenes.forEach(s => s.classList.add('in'));
    setVeil(scenes[0]);
    return;
  }
  const gsap = window.gsap;
  const ScrollTrigger = window.ScrollTrigger;
  gsap.registerPlugin(ScrollTrigger);

  if (window.Lenis) {
    const lenis = new window.Lenis({
      duration: 2.0,
      easing: t => 1 - Math.pow(1 - t, 4),
      smoothWheel: true,
      smoothTouch: false,
      wheelMultiplier: 0.68,
      touchMultiplier: 1.3,
      lerp: 0.075,
    });
    window.lenis = lenis;
    lenis.on('scroll', ScrollTrigger.update);
    gsap.ticker.add(time => lenis.raf(time * 1000));
    gsap.ticker.lagSmoothing(0);
  }

  // Render engine: WebCodecs canvas (default) or video.currentTime (fallback).
  const useWebCodecs = window.CinematicScrubber && window.CinematicScrubber.isSupported();
  if (useWebCodecs) document.body.classList.add('webcodecs-scrub');
  console.info('[__starter__] scrub:', useWebCodecs ? 'WebCodecs (canvas)' : 'video.currentTime (legacy)');

  // Per-scene scroll runway from data-scrub-duration (vh); default 1.8 viewports.
  scenes.forEach(scene => {
    const vh = parseFloat(scene.dataset.scrubDuration || '0');
    const mult = vh > 0 ? (vh / 100) : 1.8;
    scene.style.setProperty('--scene-h', (mult * 100) + 'vh');
  });

  const DOLLY = [
    { sx:1.16, x:-2, y:-1 }, { sx:1.14, x: 3, y: 1 },
    { sx:1.20, x: 0, y:-2 }, { sx:1.14, x:-3, y: 1 },
    { sx:1.16, x: 2, y:-2 }, { sx:1.16, x:-2, y: 2 },
    { sx:1.18, x: 0, y: 0 }, { sx:1.12, x: 0, y: 2 },
    { sx:1.20, x: 0, y:-3 },
  ];

  const scrubbers = new Array(videos.length).fill(null);

  if (useWebCodecs) {
    const initScrubber = (idx) => {
      const canvas = canvases[idx];
      const url = canvas && canvas.dataset.src;
      if (!canvas || !url) return Promise.resolve();
      const s = new window.CinematicScrubber(url, canvas);
      scrubbers[idx] = s;
      return s.init().catch(e => {
        console.warn('[__starter__] scrubber init failed for stage', idx, '— falling back to <video>', e);
        scrubbers[idx] = null;
        if (videos[idx]) videos[idx].style.display = 'block';
        readyVideo(videos[idx]);
      });
    };
    (async () => {
      await Promise.all([0, 1, 2].map(initScrubber));
      canvases[0] && canvases[0].classList.add('active');
      setVeil(scenes[0]);
      for (let i = 3; i < canvases.length; i++) setTimeout(() => initScrubber(i), 400 + (i - 3) * 250);
    })();
  } else {
    (async () => {
      await Promise.all(videos.slice(0, 3).map(readyVideo));
      videos[0] && videos[0].classList.add('active');
      setVeil(scenes[0]);
    })();
    videos.slice(3).forEach((v, i) => {
      const idx = i + 3;
      const trigger = scenes[Math.max(0, idx - 1)] || scenes[idx];
      if (trigger) ScrollTrigger.create({ trigger, start: 'top bottom', once: true, onEnter: () => readyVideo(v) });
    });
  }

  const localProgress = new Array(videos.length).fill(0);
  const displayed     = new Array(videos.length).fill(0);
  let lastActive = 0;

  function paintLoop() {
    const lo = Math.max(0, lastActive - 1);
    const hi = Math.min(videos.length - 1, lastActive + 1);
    for (let i = lo; i <= hi; i++) {
      displayed[i] += (localProgress[i] - displayed[i]) * 0.2;
      if (Math.abs(localProgress[i] - displayed[i]) < 0.0004) displayed[i] = localProgress[i];
      const d = DOLLY[i] || DOLLY[0];
      const k = displayed[i];
      const transform = `scale(${d.sx - k*0.05}) translate3d(${d.x*(k-0.5)*2}%, ${d.y*(k-0.5)*2}%, 0)`;

      const scr = scrubbers[i];
      if (scr && scr.ready) {
        scr.scrubTo(displayed[i]);
        if (canvases[i]) canvases[i].style.transform = transform;
        continue;
      }
      const v = videos[i];
      if (!v || !v.duration) continue;
      const t = displayed[i] * Math.max(0, v.duration - 1 / 60);
      if (Math.abs(v.currentTime - t) > 1 / 60) { try { v.currentTime = t; } catch (_) {} }
      v.style.transform = transform;
    }
    requestAnimationFrame(paintLoop);
  }
  requestAnimationFrame(paintLoop);

  function activate(idx, scene) {
    if (idx === lastActive) return;
    const pool = useWebCodecs ? canvases : videos;
    const out = pool[lastActive], inV = pool[idx];
    if (inV) inV.classList.add('active');
    setTimeout(() => { if (out && out !== inV) out.classList.remove('active'); }, 700);
    lastActive = idx;
    setVeil(scene);
  }

  scenes.forEach((scene, idx) => {
    ScrollTrigger.create({
      trigger: scene, start: 'top top', end: 'bottom bottom', scrub: true,
      onUpdate: self => { localProgress[idx] = self.progress; },
    });
    ScrollTrigger.create({
      trigger: scene, start: 'top 75%', end: 'bottom 25%',
      onEnter: () => activate(idx, scene), onEnterBack: () => activate(idx, scene),
    });
    ScrollTrigger.create({
      trigger: scene, start: 'top 65%', end: 'top top',
      onEnter: () => scene.classList.add('in'), onLeaveBack: () => scene.classList.remove('in'),
    });
  });

  // Optional: fade the stage out once trailing (hybrid) sections own the view.
  const trailing = document.querySelector('.trailing');
  if (trailing) {
    ScrollTrigger.create({
      trigger: trailing, start: 'top 70%',
      onEnter:    () => document.body.classList.add('no-stage'),
      onLeaveBack:() => document.body.classList.remove('no-stage'),
    });
  }

  window.addEventListener('resize', () => ScrollTrigger.refresh(), { passive: true });
})();
